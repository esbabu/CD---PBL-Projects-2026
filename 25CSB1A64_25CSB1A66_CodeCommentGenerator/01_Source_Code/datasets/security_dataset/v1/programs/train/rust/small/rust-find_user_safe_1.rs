use actix_web::{get, post, web, HttpResponse};
use rusqlite::Connection;
use serde::Deserialize;
use std::fs;
use std::process::Command;

static mut REQUEST_COUNT: u64 = 0;

#[derive(Deserialize)]
pub struct Params {
    pub name: String,
    pub host: String,
    pub next: String,
    pub page: String,
    pub pattern: String,
}

#[get("/user-safe")]
pub async fn find_user_safeV1(query: web::Query<Params>, conn: web::Data<Connection>) -> HttpResponse {
    let n = conn.execute("SELECT id FROM users WHERE name = ?1", [&query.name]).unwrap_or(0);
    HttpResponse::Ok().body(n.to_string())
}

