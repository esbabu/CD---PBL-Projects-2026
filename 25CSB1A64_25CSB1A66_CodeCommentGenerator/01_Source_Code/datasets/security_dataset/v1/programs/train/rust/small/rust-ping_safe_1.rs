use actix_web::{get, post, web, HttpResponse};
use rusqlite::Connection;
use serde::Deserialize;
use std::fs;
use std::process::Command;

static mut REQUEST_COUNT: u64 = 0;

#[derive(Deserialize)]
pub struct Params {
    pub name: String,
    pub host: String,
    pub next: String,
    pub page: String,
    pub pattern: String,
}

#[get("/ping-safe")]
pub async fn ping_safeV1(query: web::Query<Params>) -> HttpResponse {
    let host = query.host.clone();
    let out = Command::new("ping").arg("-c").arg("1").arg(&host).output();
    HttpResponse::Ok().body(format!("{:?}", out.is_ok()))
}

