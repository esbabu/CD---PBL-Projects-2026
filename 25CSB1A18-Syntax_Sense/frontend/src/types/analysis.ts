/**
 * Languages recognized by the SyntaxSense platform.
 */
export type SupportedLanguage = 'cpp' | 'python' | 'java';

/**
 * Request payload for POST /api/v1/analyze.
 */
export interface AnalyzeRequest {
  language: SupportedLanguage | string;
  code: string;
}

/**
 * Machine learning error classification result.
 */
export interface ClassificationResult {
  label: string;
  confidence: number;
  source: 'model' | string;
}

/**
 * Diagnostic finding produced by parser or source heuristics.
 */
export interface DiagnosticItem {
  category: string;
  origin: 'parser' | 'source_heuristic' | string;
  severity: 'error' | 'warning' | string;
  line: number | null;
  column: number | null;
  explanation: string;
  suggestion: string;
  parserMessage?: string;
}

/**
 * Target location for navigating the editor to a specific diagnostic finding.
 */
export interface DiagnosticNavigationTarget {
  line: number;
  column?: number | null;
  timestamp: number;
}

/**
 * Summary metrics of analysis findings.
 */
export interface AnalysisSummary {
  diagnosticCount: number;
  parserDiagnosticCount: number;
  sourceHeuristicDiagnosticCount: number;
}

/**
 * Lexical token generated by language lexer.
 */
export interface LexicalToken {
  type: string;
  value: string;
  line: number;
  column: number;
}

/**
 * Successful response from POST /api/v1/analyze.
 */
export interface AnalyzeResponse {
  language: string;
  analysisVersion: string;
  classification: ClassificationResult;
  diagnostics: DiagnosticItem[];
  summary: AnalysisSummary;
  tokens?: LexicalToken[];
}

/**
 * Structured validation error detail from FastAPI.
 */
export interface ApiErrorDetail {
  loc?: (string | number)[];
  msg?: string;
  type?: string;
  [key: string]: unknown;
}

/**
 * Structured error payload returned by SyntaxSense API.
 */
export interface ApiErrorPayload {
  code:
    | 'unsupported_language'
    | 'invalid_request'
    | 'invalid_source'
    | 'analysis_failed'
    | string;
  message: string;
  details?: ApiErrorDetail[] | unknown[];
}

/**
 * Standard error response envelope from the API.
 */
export interface ApiErrorResponse {
  error: ApiErrorPayload;
}
