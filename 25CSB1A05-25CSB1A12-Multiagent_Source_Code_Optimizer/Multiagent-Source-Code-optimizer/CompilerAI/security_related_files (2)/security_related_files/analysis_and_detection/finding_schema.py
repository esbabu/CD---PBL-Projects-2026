"""
Normalized Finding Schema and Deduplication Logic for C/C++ Code Analysis.

Provides a unified, structured representation for findings generated by compilers,
static analyzers (Clang-Tidy, Cppcheck), runtime sanitizers (ASan, UBSan),
rule-based scanners, and LLM reasoning.

Implements:
  - Phase 4: Canonical Defect Families & Provenance-Preserving Deduplication
  - Phase 6: Separation of Severity, Confidence Levels, and Exploitability
  - Phase 7: Six Canonical Finding Categories
"""

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional, Tuple, Set
import uuid
import re


# ── Canonical Finding Categories (Phase 7) ────────────────────────────────────
CATEGORY_SECURITY_VULNERABILITY = "security_vulnerability"
CATEGORY_POTENTIAL_SECURITY_RISK = "potential_security_risk"
CATEGORY_COMPILER_ERROR = "compiler_error"
CATEGORY_COMPILER_WARNING = "compiler_warning"
CATEGORY_CODE_QUALITY = "code_quality"
CATEGORY_PERFORMANCE_OPTIMIZATION = "performance_optimization"

CANONICAL_CATEGORIES: Set[str] = {
    CATEGORY_SECURITY_VULNERABILITY,
    CATEGORY_POTENTIAL_SECURITY_RISK,
    CATEGORY_COMPILER_ERROR,
    CATEGORY_COMPILER_WARNING,
    CATEGORY_CODE_QUALITY,
    CATEGORY_PERFORMANCE_OPTIMIZATION,
}

# ── Confidence Levels (Phase 6) ───────────────────────────────────────────────
CONFIDENCE_CONFIRMED = "confirmed"
CONFIDENCE_HIGH = "high"
CONFIDENCE_MEDIUM = "medium"
CONFIDENCE_LOW = "low"

CONFIDENCE_LEVELS: Set[str] = {
    CONFIDENCE_CONFIRMED,
    CONFIDENCE_HIGH,
    CONFIDENCE_MEDIUM,
    CONFIDENCE_LOW,
}

# ── Deduplication Configuration & Toggles ────────────────────────────────────
ENABLE_CROSS_TOOL_DEDUPLICATION: bool = True

INCIDENTAL_LINT_RULE_IDS: Set[str] = {
    "cert_err33_c",
    "cert-err33-c",
    "concurrency_mt_unsafe",
    "concurrency-mt-unsafe",
    "nullpointeroutofmemory",
    "nullpointeroutofresources",
    "unchecked_malloc",
    "taint_flow_risk",
}


@dataclass
class Finding:
    """
    Normalized finding schema representing a code defect, vulnerability,
    compiler diagnostic, or performance/quality observation.
    """
    id: str = field(default_factory=lambda: f"finding-{uuid.uuid4().hex[:8]}")
    type: str = "unknown"
    category: str = CATEGORY_SECURITY_VULNERABILITY
    description: str = ""
    severity: str = "medium"            # "critical" | "high" | "medium" | "low" | "info"
    confidence: float = 0.8             # 0.0 to 1.0
    confidence_level: str = CONFIDENCE_HIGH  # "confirmed" | "high" | "medium" | "low"
    exploitability: str = "theoretical"  # "proven" | "reachable" | "attacker_controlled" | "theoretical" | "none"
    source_tool: str = "unknown"        # "clang" | "clang-tidy" | "cppcheck" | "asan" | "ubsan" | "rule" | "llm" | "heuristic"
    detection_engine: str = "unknown"
    original_rule_id: Optional[str] = None
    canonical_defect_family: str = "other"
    file_path: str = "<source>"
    line: Optional[int] = None
    column: Optional[int] = None
    start_line: Optional[int] = None
    end_line: Optional[int] = None
    start_column: Optional[int] = None
    end_column: Optional[int] = None
    code_snippet: Optional[str] = None
    evidence: str = ""
    recommendation: str = ""
    cwe_id: Optional[str] = None
    contributing_engines: List[str] = field(default_factory=list)
    contributing_rule_ids: List[str] = field(default_factory=list)
    execution_context: Dict[str, Any] = field(default_factory=dict)
    status: str = "potential"           # "confirmed" | "potential" | "suspicious" | "code_quality" | "manual_review" | "unrun"
    is_confirmed: bool = False
    related_findings: List[str] = field(default_factory=list)
    raw_diagnostic: Optional[str] = None

    def __post_init__(self):
        # Sync line coordinates
        if self.line is not None:
            if self.start_line is None:
                self.start_line = self.line
            if self.end_line is None:
                self.end_line = self.line
        elif self.start_line is not None:
            self.line = self.start_line
            if self.end_line is None:
                self.end_line = self.start_line

        # Sync column coordinates
        if self.column is not None and self.start_column is None:
            self.start_column = self.column

        # Sync detection_engine and source_tool
        if self.detection_engine == "unknown" and self.source_tool != "unknown":
            self.detection_engine = self.source_tool
        elif self.source_tool == "unknown" and self.detection_engine != "unknown":
            self.source_tool = self.detection_engine

        # Sync contributing engines
        if not self.contributing_engines and self.source_tool != "unknown":
            self.contributing_engines = [self.source_tool]

        # Sync original_rule_id
        if self.original_rule_id and self.original_rule_id not in self.contributing_rule_ids:
            self.contributing_rule_ids.append(self.original_rule_id)

        # Derive confidence level from float/bool if not explicitly set
        if self.is_confirmed or self.status == "confirmed":
            self.confidence_level = CONFIDENCE_CONFIRMED
            if self.confidence is None or self.confidence == 0.8:
                self.confidence = 1.0
        elif self.confidence_level not in CONFIDENCE_LEVELS:
            if self.confidence >= 0.95:
                self.confidence_level = CONFIDENCE_CONFIRMED
            elif self.confidence >= 0.75:
                self.confidence_level = CONFIDENCE_HIGH
            elif self.confidence >= 0.45:
                self.confidence_level = CONFIDENCE_MEDIUM
            else:
                self.confidence_level = CONFIDENCE_LOW

        # Ensure canonical category is populated
        self.category = classify_finding_category(self.to_dict())

    def to_dict(self) -> Dict[str, Any]:
        """Convert finding to standard dictionary representation."""
        data = asdict(self)
        data["source"] = self.source_tool
        return data

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Finding":
        """Construct Finding from dictionary, preserving existing fields."""
        cleaned = dict(data)
        if "source" in cleaned and "source_tool" not in cleaned:
            cleaned["source_tool"] = cleaned["source"]
        if "source_tool" in cleaned and "detection_engine" not in cleaned:
            cleaned["detection_engine"] = cleaned["source_tool"]

        valid_keys = {
            "id", "type", "category", "description", "severity", "confidence",
            "confidence_level", "exploitability", "source_tool", "detection_engine",
            "original_rule_id", "canonical_defect_family", "file_path", "line",
            "column", "start_line", "end_line", "start_column", "end_column",
            "code_snippet", "evidence", "recommendation", "cwe_id",
            "contributing_engines", "contributing_rule_ids", "execution_context",
            "status", "is_confirmed", "related_findings", "raw_diagnostic"
        }
        filtered = {k: v for k, v in cleaned.items() if k in valid_keys}

        # Safe line parsing
        for line_key in ("line", "start_line", "end_line"):
            if line_key in filtered:
                val = filtered[line_key]
                if isinstance(val, list):
                    filtered[line_key] = int(val[0]) if val and str(val[0]).isdigit() else None
                elif val is not None:
                    try:
                        filtered[line_key] = int(val)
                    except (ValueError, TypeError):
                        filtered[line_key] = None

        for col_key in ("column", "start_column", "end_column"):
            if col_key in filtered and filtered[col_key] is not None:
                try:
                    filtered[col_key] = int(filtered[col_key])
                except (ValueError, TypeError):
                    filtered[col_key] = None

        if "id" not in filtered or not filtered["id"]:
            filtered["id"] = f"finding-{uuid.uuid4().hex[:8]}"
        return cls(**filtered)


def classify_finding_category(finding: Dict[str, Any]) -> str:
    """
    Classify finding into one of the 6 canonical categories (Phase 7):
      - security_vulnerability: Genuine security defects (CWE mapped, high/confirmed confidence)
      - potential_security_risk: Suspicious patterns requiring human review or context
      - compiler_error: Syntax errors, compilation failures, fatal diagnostics
      - compiler_warning: General compiler diagnostics not directly demonstrating a vulnerability
      - code_quality: Linter notices, modernization suggestions, style issues
      - performance_optimization: Algorithmic inefficiencies, unnecessary copies
    """
    current_cat = finding.get("category", "")
    if current_cat in CANONICAL_CATEGORIES:
        return current_cat

    ftype = str(finding.get("type", "")).lower()
    desc = str(finding.get("description", "")).lower()
    raw = str(finding.get("raw_diagnostic", "")).lower()
    source = str(finding.get("source_tool", finding.get("source", ""))).lower()
    sev = str(finding.get("severity", "medium")).lower()
    conf_level = str(finding.get("confidence_level", "")).lower()
    cwe_id = finding.get("cwe_id")

    # 1. Compiler errors
    if "error" in ftype or "error:" in raw or "fatal error" in raw or (source in ("clang", "clang++") and "error" in sev):
        if not ("sanitizer" in ftype or "runtime_violation" in ftype):
            return CATEGORY_COMPILER_ERROR

    # 2. Performance optimization
    if "performance" in ftype or "performance" in desc or current_cat == "performance":
        return CATEGORY_PERFORMANCE_OPTIMIZATION

    # 3. Code quality / style
    if any(k in ftype for k in ("modernize", "readability", "style", "unused", "cstylecast", "shadowvariable", "cert_err33", "cert-err33")) or (not cwe_id and "bugprone" in ftype and "use_after_move" not in ftype):
        return CATEGORY_CODE_QUALITY
    if current_cat == "quality":
        return CATEGORY_CODE_QUALITY

    # 4. Compiler warnings
    if source in ("clang", "clang++") and ("compiler_diagnostic" in ftype or "[-w" in raw or ftype.startswith("clang_-w")):
        # Only treat as warning if not a recognized severe security defect
        if not cwe_id and not any(k in ftype for k in ("security", "overflow", "format", "null_dereference")):
            return CATEGORY_COMPILER_WARNING

    # 5. Potential security risk vs confirmed security vulnerability
    if any(k in ftype for k in ("potential", "suspicious", "xml_pattern", "insecure_prng", "open_redirect", "log_injection")):
        return CATEGORY_POTENTIAL_SECURITY_RISK

    if conf_level in (CONFIDENCE_LOW, "medium") and not finding.get("is_confirmed"):
        if "potential" in finding.get("status", "") or "suspicious" in finding.get("status", ""):
            return CATEGORY_POTENTIAL_SECURITY_RISK

    if cwe_id or current_cat == "security" or any(k in ftype for k in (
        "overflow", "injection", "free", "leak", "dereference", "xss", "traversal",
        "deadlock", "race", "aes", "rsa", "secret", "password", "backdoor", "toctou"
    )):
        return CATEGORY_SECURITY_VULNERABILITY

    if source in ("clang", "clang++"):
        return CATEGORY_COMPILER_WARNING

    return CATEGORY_POTENTIAL_SECURITY_RISK


def canonical_defect_family(finding: Dict[str, Any]) -> str:
    """
    Map check names, CWEs, and diagnostics to a Canonical Defect Family (Phase 4).
    Prevents false merging of different defect types while unifying multi-engine detections.
    """
    ftype = str(finding.get("type", "")).lower().replace("-", "_")
    cwe = str(finding.get("cwe_id", "")).upper()
    desc = str(finding.get("description", "")).lower()

    if "taint_flow" in ftype:
        return "taint_flow"

    # Memory corruption & buffer overflows (CWE-120, 121, 122, 125, 170, 193, 787, 788)
    if cwe in ("CWE-120", "CWE-121", "CWE-122", "CWE-125", "CWE-170", "CWE-193", "CWE-787", "CWE-788") or \
       any(k in ftype for k in ("buffer_overflow", "heap_overflow", "stack_overflow", "strcpy", "strcat", "sprintf", "off_by_one", "out_of_bounds", "deprecatedorunsafebufferhandling")):
        return "buffer_overflow"

    # Format string (CWE-134, 1336)
    if cwe in ("CWE-134", "CWE-1336") or any(k in ftype for k in ("format_string", "format_security", "format_nonliteral", "format_overflow", "format_truncation", "diagnostic_format", "wformat", "clang_format")):
        return "format_string"

    # Command injection (CWE-78, 88)
    if cwe in ("CWE-78", "CWE-88") or any(k in ftype for k in ("command_injection", "popen", "system_injection", "shell")):
        return "command_injection"

    # SQL injection (CWE-89)
    if cwe == "CWE-89" or "sql_injection" in ftype or "sql" in ftype:
        return "sql_injection"

    # XSS (CWE-79)
    if cwe == "CWE-79" or "xss" in ftype:
        return "xss"

    # Path traversal (CWE-22, 23, 73)
    if cwe in ("CWE-22", "CWE-23", "CWE-73") or any(k in ftype for k in ("path_traversal", "zip_slip")):
        return "path_traversal"

    # Return stack address (CWE-562)
    if cwe == "CWE-562" or any(k in ftype for k in ("return_stack", "returndanglinglifetime")):
        return "return_stack_address"

    # Use after free (CWE-416)
    if cwe == "CWE-416" or "use_after_free" in ftype or ("dangling" in ftype and "return" not in ftype):
        return "use_after_free"

    # Double free (CWE-415)
    if cwe == "CWE-415" or "double_free" in ftype:
        return "double_free"

    # Resource leak (CWE-401, 775)
    if cwe in ("CWE-401", "CWE-775") or "memory_leak" in ftype or "descriptor_leak" in ftype:
        return "resource_leak"

    # Null pointer dereference (CWE-476)
    if cwe == "CWE-476" or any(k in ftype for k in ("null_dereference", "null_pointer", "nullderef")):
        return "null_dereference"

    # Uninitialized variable (CWE-457)
    if cwe == "CWE-457" or "uninitialized" in ftype:
        return "uninitialized_variable"

    # Integer overflow / truncation / sign mismatch (CWE-190, 195, 197, 1335)
    if cwe in ("CWE-190", "CWE-195", "CWE-197", "CWE-1335") or any(k in ftype for k in ("integer_overflow", "signed_unsigned", "truncation")):
        return "integer_overflow"

    # Array bounds (CWE-129)
    if cwe in ("CWE-129",) or any(k in ftype for k in ("array_index", "negative_index", "arrayindexoutofbounds")):
        return "array_bounds"

    # Hardcoded credential / secrets (CWE-798, 1392, 321)
    if cwe in ("CWE-798", "CWE-1392", "CWE-321") or any(k in ftype for k in ("hardcoded_password", "hardcoded_api_key", "hardcoded_aes_key", "default_credentials", "hardcoded_secret")):
        return "hardcoded_credential"

    # Weak cryptography (CWE-326, 327, 328, 329, 261)
    if cwe in ("CWE-326", "CWE-327", "CWE-328", "CWE-329", "CWE-261") or any(k in ftype for k in ("weak_hash", "xor_encryption", "rsa_key_length", "static_iv", "encoding_not_encryption")):
        return "weak_cryptography"

    # Insecure randomness (CWE-330, 337, 338)
    if cwe in ("CWE-330", "CWE-337", "CWE-338") or any(k in ftype for k in ("insecure_prng", "predictable_seed", "sequential_session")):
        return "insecure_randomness"

    # Sensitive data exposure (CWE-200, 209, 256, 319, 532)
    if cwe in ("CWE-200", "CWE-209", "CWE-256", "CWE-319", "CWE-532") or any(k in ftype for k in ("plaintext_password", "password_in_log", "verbose_error", "cleartext_transmission", "information_exposure")):
        return "sensitive_data_exposure"

    # Race condition / Concurrency (CWE-362, 367, 479, 833)
    if cwe in ("CWE-362", "CWE-367", "CWE-479", "CWE-833") or any(k in ftype for k in ("deadlock", "data_race", "toctou", "async_signal")):
        return "race_condition_concurrency"

    # DoS / Resource exhaustion (CWE-400, 674, 770, 1285, 1333)
    if cwe in ("CWE-400", "CWE-674", "CWE-770", "CWE-1285", "CWE-1333") or any(k in ftype for k in ("uncontrolled_recursion", "alloca", "vla", "slowloris", "redos")):
        return "dos_resource_exhaustion"

    # Mismatched deallocation / virtual destructor (CWE-404, 762, 1325)
    if cwe in ("CWE-404", "CWE-762", "CWE-1325") or any(k in ftype for k in ("mismatched_alloc", "virtualdestructor", "mismatchallocdealloc", "mismatched_new_delete")):
        return "mismatched_alloc_dealloc"

    # Timing side channel (CWE-208)
    if cwe in ("CWE-208",) or any(k in ftype for k in ("timing", "side_channel", "non_constant_time")):
        return "timing_side_channel"

    # Access control & privileges
    if cwe in ("CWE-243", "CWE-250", "CWE-276", "CWE-295", "CWE-306", "CWE-307", "CWE-657", "CWE-732", "CWE-912", "CWE-942", "CWE-1327") or any(k in ftype for k in ("backdoor", "tls_verification", "permissions", "umask", "cors", "bind_all")):
        return "access_control_security"

    # Input validation / output handling
    if cwe in ("CWE-20", "CWE-90", "CWE-113", "CWE-117", "CWE-252", "CWE-601", "CWE-611", "CWE-697", "CWE-918") or any(k in ftype for k in ("ldap", "crlf", "log_injection", "xxe", "ssrf", "open_redirect", "unchecked_io", "pointer_comparison")):
        return "input_validation_output_handling"

    # Undefined behavior
    if cwe in ("CWE-14", "CWE-369") or any(k in ftype for k in ("division_by_zero", "memset_key")):
        return "undefined_behavior"

    return ftype or "other"


def normalize_finding(raw: Dict[str, Any], default_source: str = "unknown") -> Dict[str, Any]:
    """Ensure dictionary complies with the Finding schema and canonical classifications."""
    if isinstance(raw, Finding):
        f = raw
    else:
        f = Finding.from_dict(raw)

    if f.source_tool == "unknown" and default_source != "unknown":
        f.source_tool = default_source
        f.detection_engine = default_source
        if not f.contributing_engines:
            f.contributing_engines = [default_source]

    # Populate canonical defect family
    f.canonical_defect_family = canonical_defect_family(f.to_dict())
    f.category = classify_finding_category(f.to_dict())

    return f.to_dict()


def _legacy_deduplicate_findings(findings: List[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Legacy strict exact-line finding deduplication."""
    if not findings:
        return [], {
            "original_count": 0,
            "deduplicated_count": 0,
            "merged_groups": 0,
            "multi_engine_count": 0,
            "engine_overlap_distribution": {"1_engine": 0, "2_engines": 0, "3+_engines": 0},
        }

    sev_rank = {"critical": 5, "high": 4, "medium": 3, "low": 2, "info": 1}
    conf_rank = {CONFIDENCE_CONFIRMED: 4, CONFIDENCE_HIGH: 3, CONFIDENCE_MEDIUM: 2, CONFIDENCE_LOW: 1}

    groups: Dict[Tuple[str, Optional[int]], List[Dict[str, Any]]] = {}
    for raw_f in findings:
        f = normalize_finding(raw_f)
        line_val = f.get("line")
        fam = f.get("canonical_defect_family") or canonical_defect_family(f)
        groups.setdefault((fam, line_val), []).append(f)

    merged_findings: List[Dict[str, Any]] = []
    merged_groups_count = 0
    overlap_dist = {"1_engine": 0, "2_engines": 0, "3+_engines": 0}
    multi_engine_count = 0

    for (fam, line_val), group in groups.items():
        if len(group) == 1:
            item = group[0]
            engines = list(dict.fromkeys(item.get("contributing_engines") or [item.get("source_tool", "unknown")]))
            item["contributing_engines"] = engines
            if "execution_context" not in item or not isinstance(item["execution_context"], dict):
                item["execution_context"] = {}
            item["execution_context"]["provenance_sources"] = list(engines)
            num_eng = len(engines)
            if num_eng >= 3:
                overlap_dist["3+_engines"] += 1
                multi_engine_count += 1
            elif num_eng == 2:
                overlap_dist["2_engines"] += 1
                multi_engine_count += 1
            else:
                overlap_dist["1_engine"] += 1
            merged_findings.append(item)
            continue

        merged_groups_count += 1
        group.sort(
            key=lambda item: (
                conf_rank.get(item.get("confidence_level", CONFIDENCE_MEDIUM), 2),
                sev_rank.get(str(item.get("severity", "medium")).lower(), 2),
                item.get("confidence", 0.5),
                len(item.get("description", "")),
            ),
            reverse=True,
        )

        primary = dict(group[0])
        all_ids = [item.get("id") for item in group if item.get("id")]
        all_engines: List[str] = []
        all_rule_ids: List[str] = []
        all_evidences: List[str] = []
        all_cwes: List[str] = []

        for item in group:
            for eng in item.get("contributing_engines", []) or [item.get("source_tool", "unknown")]:
                if eng and eng not in all_engines and eng != "unknown":
                    all_engines.append(eng)
            rule_id = item.get("original_rule_id") or item.get("type")
            if rule_id and rule_id not in all_rule_ids:
                all_rule_ids.append(rule_id)
            ev = item.get("evidence")
            if ev and ev not in all_evidences:
                all_evidences.append(ev)
            cwe = item.get("cwe_id")
            if cwe and cwe not in all_cwes:
                all_cwes.append(cwe)

        if not all_engines:
            all_engines = [primary.get("source_tool", "unknown")]

        primary["related_findings"] = [i for i in all_ids if i != primary.get("id")]
        primary["contributing_engines"] = all_engines
        primary["contributing_rule_ids"] = all_rule_ids
        primary["canonical_defect_family"] = fam
        if "execution_context" not in primary or not isinstance(primary["execution_context"], dict):
            primary["execution_context"] = {}
        primary["execution_context"]["provenance_sources"] = list(all_engines)

        if len(all_engines) >= 2:
            multi_engine_count += 1
            primary["confidence_level"] = CONFIDENCE_CONFIRMED
            primary["confidence"] = 1.0
            primary["is_confirmed"] = True
            primary["status"] = "confirmed"

        num_eng = len(all_engines)
        if num_eng >= 3:
            overlap_dist["3+_engines"] += 1
        elif num_eng == 2:
            overlap_dist["2_engines"] += 1
        else:
            overlap_dist["1_engine"] += 1

        if any(item.get("is_confirmed") or item.get("status") == "confirmed" or item.get("confidence_level") == CONFIDENCE_CONFIRMED for item in group):
            primary["is_confirmed"] = True
            primary["status"] = "confirmed"
            primary["confidence_level"] = CONFIDENCE_CONFIRMED
            primary["confidence"] = 1.0

        if all_cwes and not primary.get("cwe_id"):
            primary["cwe_id"] = all_cwes[0]
        if all_evidences:
            primary["evidence"] = " | ".join(all_evidences)

        primary["category"] = classify_finding_category(primary)
        merged_findings.append(primary)

    merged_findings.sort(
        key=lambda item: (
            item.get("line") if item.get("line") is not None else 999999,
            -sev_rank.get(str(item.get("severity", "medium")).lower(), 2),
        )
    )

    return merged_findings, {
        "original_count": len(findings),
        "deduplicated_count": len(merged_findings),
        "merged_groups": merged_groups_count,
        "multi_engine_count": multi_engine_count,
        "engine_overlap_distribution": overlap_dist,
    }


def deduplicate_findings(findings: List[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """
    Intelligent Finding Deduplication (Option A - Per-Location Cards with Multi-Engine Consolidation):
    
    1. Multiple software engines (Clang-Tidy, Cppcheck, Rule Engine, Compiler) flagging the
       SAME defect location (within +/- 2 lines) collapse into ONE primary finding card.
    2. Different error locations in code (e.g. line 12 vs line 80) remain SEPARATE cards so each
       can be audited and jumped to in the editor individually.
    3. Incidental lints on high/critical security statements (e.g. cert-err33-c, unchecked_malloc,
       concurrency-mt-unsafe) are subsumed into the primary security defect card.
    4. Distinct defect types on the same line (e.g. buffer overflow vs division by zero) are NOT
       merged unless one is an incidental lint of the other.
    5. Fully records contributing engines in `contributing_engines` and `execution_context["provenance_sources"]`.
    6. Multi-engine corroboration elevates confidence to 1.0 (CONFIRMED).
    """
    if not ENABLE_CROSS_TOOL_DEDUPLICATION:
        return _legacy_deduplicate_findings(findings)

    if not findings:
        return [], {
            "original_count": 0,
            "deduplicated_count": 0,
            "merged_groups": 0,
            "multi_engine_count": 0,
            "engine_overlap_distribution": {"1_engine": 0, "2_engines": 0, "3+_engines": 0},
        }

    sev_rank = {"critical": 5, "high": 4, "medium": 3, "low": 2, "info": 1}
    conf_rank = {CONFIDENCE_CONFIRMED: 4, CONFIDENCE_HIGH: 3, CONFIDENCE_MEDIUM: 2, CONFIDENCE_LOW: 1}

    # Group by file_path first
    by_file: Dict[str, List[Dict[str, Any]]] = {}
    for raw_f in findings:
        f = normalize_finding(raw_f)
        fp = f.get("file_path") or "<source>"
        by_file.setdefault(fp, []).append(f)

    merged_findings: List[Dict[str, Any]] = []
    merged_groups_count = 0
    overlap_dist = {"1_engine": 0, "2_engines": 0, "3+_engines": 0}
    multi_engine_count = 0

    def finding_precedence(item: Dict[str, Any]) -> Tuple[int, int, int, int, float, int]:
        t = str(item.get("type", "")).lower().replace("-", "_")
        r = str(item.get("original_rule_id", "")).lower().replace("-", "_")
        is_inc = any(inc in t or inc in r for inc in INCIDENTAL_LINT_RULE_IDS)
        has_cwe = 1 if item.get("cwe_id") else 0
        s_rank = sev_rank.get(str(item.get("severity", "medium")).lower(), 2)
        c_rank = conf_rank.get(item.get("confidence_level", CONFIDENCE_MEDIUM), 2)
        c_float = float(item.get("confidence", 0.5))
        d_len = len(item.get("description", ""))
        return (0 if is_inc else 1, s_rank, has_cwe, c_rank, c_float, d_len)

    for fp, file_findings in by_file.items():
        # Sort by line, then priority
        file_findings.sort(
            key=lambda item: (
                item.get("line") if item.get("line") is not None else 999999,
                -finding_precedence(item)[0],
                -finding_precedence(item)[2],
            )
        )

        used_indices: Set[int] = set()
        n = len(file_findings)

        for i in range(n):
            if i in used_indices:
                continue

            f1 = file_findings[i]
            cluster = [f1]
            used_indices.add(i)

            l1 = f1.get("line")
            fam1 = f1.get("canonical_defect_family") or canonical_defect_family(f1)
            cwe1 = (f1.get("cwe_id") or "").upper()
            t1 = str(f1.get("type", "")).lower().replace("-", "_")
            r1 = str(f1.get("original_rule_id", "")).lower().replace("-", "_")
            is_inc1 = any(inc in t1 or inc in r1 for inc in INCIDENTAL_LINT_RULE_IDS)

            for j in range(i + 1, n):
                if j in used_indices:
                    continue

                f2 = file_findings[j]
                l2 = f2.get("line")

                # Line distance check
                if l1 is not None and l2 is not None:
                    dist = abs(l1 - l2)
                elif l1 is None and l2 is None:
                    dist = 0
                else:
                    dist = 999999

                # Must be at the same code location (within +/- 2 lines)
                if dist > 2:
                    continue

                fam2 = f2.get("canonical_defect_family") or canonical_defect_family(f2)
                cwe2 = (f2.get("cwe_id") or "").upper()
                t2 = str(f2.get("type", "")).lower().replace("-", "_")
                r2 = str(f2.get("original_rule_id", "")).lower().replace("-", "_")
                is_inc2 = any(inc in t2 or inc in r2 for inc in INCIDENTAL_LINT_RULE_IDS)

                # Matching conditions
                same_fam = (fam1 == fam2 and fam1 not in ("", "other"))
                same_cwe = bool(cwe1 and cwe2 and cwe1 == cwe2)
                both_mem = (fam1 in ("buffer_overflow", "array_bounds") and fam2 in ("buffer_overflow", "array_bounds"))
                subsume_inc = (is_inc1 and not is_inc2) or (is_inc2 and not is_inc1)
                both_race = (fam1 == "race_condition_concurrency" and fam2 == "race_condition_concurrency")
                both_timing = (fam1 == "timing_side_channel" and fam2 == "timing_side_channel")
                # Collapse any findings on the exact same line into one primary card
                exact_same_line = (l1 is not None and l1 == l2)

                if same_fam or same_cwe or both_mem or subsume_inc or both_race or both_timing or exact_same_line:
                    cluster.append(f2)
                    used_indices.add(j)

            # Consolidate cluster into a single primary finding
            if len(cluster) == 1:
                item = dict(cluster[0])
                engines = list(dict.fromkeys(item.get("contributing_engines") or [item.get("source_tool", "unknown")]))
                if not engines:
                    engines = [item.get("source_tool", "unknown")]
                item["contributing_engines"] = engines
                if "execution_context" not in item or not isinstance(item["execution_context"], dict):
                    item["execution_context"] = {}
                item["execution_context"]["provenance_sources"] = list(engines)

                num_eng = len(engines)
                if num_eng >= 3:
                    overlap_dist["3+_engines"] += 1
                    multi_engine_count += 1
                elif num_eng == 2:
                    overlap_dist["2_engines"] += 1
                    multi_engine_count += 1
                else:
                    overlap_dist["1_engine"] += 1

                merged_findings.append(item)
                continue

            merged_groups_count += 1

            # Select primary finding
            cluster.sort(key=finding_precedence, reverse=True)
            primary = dict(cluster[0])

            all_ids = [item.get("id") for item in cluster if item.get("id")]
            all_engines: List[str] = []
            all_rule_ids: List[str] = []
            all_evidences: List[str] = []
            all_cwes: List[str] = []

            for item in cluster:
                eng_list = item.get("contributing_engines") or [item.get("source_tool", "unknown")]
                for eng in eng_list:
                    if eng and eng not in all_engines and eng != "unknown":
                        all_engines.append(eng)
                for rid in (item.get("contributing_rule_ids") or []) + [item.get("original_rule_id"), item.get("type")]:
                    if rid and rid not in all_rule_ids:
                        all_rule_ids.append(rid)
                ev = item.get("evidence")
                if ev and ev not in all_evidences:
                    all_evidences.append(ev)
                cwe = item.get("cwe_id")
                if cwe and cwe not in all_cwes:
                    all_cwes.append(cwe)

            if not all_engines:
                all_engines = [primary.get("source_tool", "unknown")]

            primary["related_findings"] = [i for i in all_ids if i != primary.get("id")]
            primary["contributing_engines"] = all_engines
            primary["contributing_rule_ids"] = all_rule_ids
            primary["canonical_defect_family"] = fam1 if fam1 not in ("", "other") else primary.get("canonical_defect_family", "other")
            if "execution_context" not in primary or not isinstance(primary["execution_context"], dict):
                primary["execution_context"] = {}
            primary["execution_context"]["provenance_sources"] = list(all_engines)

            num_eng = len(all_engines)
            if num_eng >= 2:
                multi_engine_count += 1
                primary["confidence"] = 1.0
                primary["confidence_level"] = CONFIDENCE_CONFIRMED
                primary["is_confirmed"] = True
                primary["status"] = "confirmed"

            if num_eng >= 3:
                overlap_dist["3+_engines"] += 1
            elif num_eng == 2:
                overlap_dist["2_engines"] += 1
            else:
                overlap_dist["1_engine"] += 1

            if any(item.get("is_confirmed") or item.get("status") == "confirmed" or item.get("confidence_level") == CONFIDENCE_CONFIRMED for item in cluster):
                primary["is_confirmed"] = True
                primary["status"] = "confirmed"
                primary["confidence_level"] = CONFIDENCE_CONFIRMED
                primary["confidence"] = 1.0

            # Ensure highest severity from cluster
            max_sev = max([str(item.get("severity", "medium")).lower() for item in cluster], key=lambda s: sev_rank.get(s, 2))
            primary["severity"] = max_sev

            unique_cwes = list(dict.fromkeys([c for c in all_cwes if c]))
            if unique_cwes:
                primary["cwe_id"] = ", ".join(unique_cwes)
            if not primary.get("recommendation"):
                for it in cluster:
                    if it.get("recommendation"):
                        primary["recommendation"] = it["recommendation"]
                        break
            if all_evidences:
                primary["evidence"] = " | ".join(all_evidences)

            primary["category"] = classify_finding_category(primary)
            merged_findings.append(primary)

    # Sort merged findings by line number, then severity
    merged_findings.sort(
        key=lambda item: (
            item.get("line") if item.get("line") is not None else 999999,
            -sev_rank.get(str(item.get("severity", "medium")).lower(), 2),
        )
    )

    summary = {
        "original_count": len(findings),
        "deduplicated_count": len(merged_findings),
        "merged_groups": merged_groups_count,
        "multi_engine_count": multi_engine_count,
        "engine_overlap_distribution": overlap_dist,
    }
    return merged_findings, summary
